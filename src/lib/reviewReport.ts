import { INTRO_ID, type Block, type Course } from '../types/course'
import type { CourseIssue } from '../export/courseCheck'
import type { LayoutIssue, LayoutIssueKind, LayoutReview } from './layoutReview'
import common from '../i18n/locales/common'

// review.md: what Scormly found in the course when the .zip was saved — the
// rendered layout (layoutReview.ts) and the pre-export content check. Written
// for AI assistants (and authors) who get the .zip but can't run Scormly.

export const REVIEW_FILE = 'review.md'

const KIND: Record<LayoutIssueKind, { title: string; fix: string }> = {
  offscreen: {
    title: 'Runs past the screen edge',
    fix: 'Part of it is hidden past the right edge, or the page scrolls sideways. Usually a long unbroken word, URL or code line, or an element that is too wide: shorten it, add spaces or line breaks, or split the table.',
  },
  spill: {
    title: 'Spills out of its block',
    fix: 'Text sticks out of its box into the neighbouring space. Shorten it or break long words.',
  },
  clipped: {
    title: 'Text is cut off',
    fix: 'A fixed-size box (card, button, label, tab) hides part of the text. Shorten the text.',
  },
  scroll: {
    title: 'Scrolls sideways inside its box',
    fix: 'Fine for code; for a table consider fewer or narrower columns so it reads on phones.',
  },
  image: {
    title: 'Image failed to load',
    fix: 'The file is missing or broken: check that the path exists in assets/ (or that the URL works).',
  },
}

// Most harmful first.
const ORDER: LayoutIssueKind[] = ['offscreen', 'clipped', 'spill', 'image', 'scroll']

const WIDTH_NAME: Record<number, string> = { 375: 'phone', 1280: 'desktop' }
const widthLabel = (w: number) => (WIDTH_NAME[w] ? `${WIDTH_NAME[w]} ${w}px` : `${w}px`)

export interface ReviewInput {
  checkIssues: CourseIssue[]
  /** The layout pass, or why it could not run. */
  layout: LayoutReview | { error: string }
  date: Date
}

export function buildReviewReport(course: Course, { checkIssues, layout, date }: ReviewInput): string {
  const blocks = blockIndex(course)
  // `heading`: a layout issue outside any block is in the lesson heading.
  const where = (lessonId: string | undefined, blockId: string | undefined, heading = false) => {
    const lesson =
      lessonId === INTRO_ID
        ? 'cover page'
        : (() => {
            const i = course.lessons.findIndex((l) => l.id === lessonId)
            return i < 0 ? 'course' : `lesson ${i + 1} “${short(course.lessons[i].title)}” (\`${lessonId}\`)`
          })()
    if (!blockId) return heading && lessonId !== INTRO_ID ? `${lesson}, lesson heading` : lesson
    const block = blocks.get(blockId)
    return `${lesson}, block \`${blockId}\`${block ? ` (${block.type})` : ''}`
  }

  const out: string[] = [
    '# Scormly review',
    '',
    `Generated by Scormly on ${date.toISOString().slice(0, 16).replace('T', ' ')} UTC when this .zip was saved,`,
    'for the course in `project.json`. Scormly rewrites this file on every save — don’t edit it.',
    'Fix the items below in `project.json` (see `AGENTS.md`); the author re-saves the .zip to get a fresh review.',
    '',
  ]

  out.push('## Layout', '')
  if ('error' in layout) {
    out.push(`The layout check could not run: ${layout.error}`, '')
  } else {
    out.push(
      `Every lesson was rendered in the real learner player at ${layout.widths.map(widthLabel).join(' and ')}`,
      'with all Continue gates open. Hidden content (closed accordion items, other tabs, scenario',
      'branches not taken) is not measured.',
      '',
    )
    const issues = [...layout.issues].sort((a, b) => ORDER.indexOf(a.kind) - ORDER.indexOf(b.kind))
    if (!issues.length) out.push('No layout problems found.', '')
    for (const kind of ORDER) {
      const group = issues.filter((i) => i.kind === kind)
      if (!group.length) continue
      out.push(`### ${KIND[kind].title} (${group.length})`, '', KIND[kind].fix, '')
      for (const issue of group) out.push(layoutLine(issue, where))
      out.push('')
    }
  }

  out.push('## Content check', '', 'The same checks Scormly runs before exporting.', '')
  if (!checkIssues.length) out.push('No issues found.', '')
  else {
    const en = common.en as Record<string, string>
    for (const issue of checkIssues) {
      const tag = issue.a11y ? 'Accessibility' : issue.severity === 'info' ? 'Tip' : 'Problem'
      out.push(`- **${tag}:** ${fill(en[issue.key] ?? issue.key, issue.vars)} — ${where(issue.lessonId, issue.blockId)}`)
    }
    out.push('')
  }
  return out.join('\n')
}

function layoutLine(issue: LayoutIssue, where: (l: string, b: string, heading: boolean) => string): string {
  const widths = [...issue.widths].sort((a, b) => a - b).map(widthLabel).join(', ')
  const samples = issue.samples.map((s) => `“${s.replace(/`/g, "'")}”`).join(', ')
  return `- ${where(issue.lessonId, issue.blockId, true)} — at ${widths}${samples ? `: ${samples}` : ''}`
}

const short = (s: string) => (s.length > 60 ? `${s.slice(0, 57)}…` : s)

function fill(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str
  return str.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

function blockIndex(course: Course): Map<string, Block> {
  const map = new Map<string, Block>()
  for (const b of course.intro?.blocks ?? []) map.set(b.id, b)
  for (const l of course.lessons) for (const b of l.blocks) map.set(b.id, b)
  return map
}
